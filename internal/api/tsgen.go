package api

import (
	"fmt"
	"io"
	"reflect"
	"slices"
	"strings"
	"time"
)

// GenerateTS writes TypeScript interfaces for Types and the event names.
func GenerateTS(w io.Writer) error {
	if err := generate(w, Types); err != nil {
		return err
	}
	var names []string
	for _, e := range Events {
		names = append(names, fmt.Sprintf("%q", e))
	}
	_, err := fmt.Fprintf(w, "\nexport const EVENTS = [%s] as const;\nexport type EventName = (typeof EVENTS)[number];\n", strings.Join(names, ", "))
	return err
}

var timeType = reflect.TypeOf(time.Time{})

type gen struct {
	out   []string
	done  map[reflect.Type]string
	names map[string]reflect.Type
}

func generate(w io.Writer, types []any) error {
	g := &gen{done: map[reflect.Type]string{}, names: map[string]reflect.Type{}}
	for _, v := range types {
		g.ts(reflect.TypeOf(v))
	}
	if _, err := io.WriteString(w, "// Code generated by internal/api/tsgen. DO NOT EDIT.\n"); err != nil {
		return err
	}
	for _, block := range g.out {
		if _, err := io.WriteString(w, "\n"+block); err != nil {
			return err
		}
	}
	return nil
}

// ts returns the TypeScript type for t, emitting an interface for structs.
func (g *gen) ts(t reflect.Type) string {
	switch {
	case t == timeType:
		return "string"
	case t.Kind() == reflect.Pointer:
		return g.ts(t.Elem()) + " | null"
	case t.Kind() == reflect.Slice || t.Kind() == reflect.Array:
		return g.wrap(g.ts(t.Elem())) + "[] | null"
	case t.Kind() == reflect.Map:
		return "Record<string, " + g.ts(t.Elem()) + "> | null"
	case t.Kind() == reflect.Interface:
		return "unknown"
	case t.Kind() == reflect.Bool:
		return "boolean"
	case t.Kind() == reflect.String:
		return "string"
	case t.Kind() >= reflect.Int && t.Kind() <= reflect.Float64:
		return "number"
	case t.Kind() == reflect.Struct:
		return g.iface(t)
	}
	return "unknown"
}

func (g *gen) wrap(s string) string {
	if strings.Contains(s, "|") {
		return "(" + s + ")"
	}
	return s
}

func (g *gen) iface(t reflect.Type) string {
	if name, ok := g.done[t]; ok {
		return name
	}
	name := t.Name()
	if other, taken := g.names[name]; taken && other != t {
		parts := strings.Split(t.PkgPath(), "/")
		pkg := parts[len(parts)-1]
		name = strings.ToUpper(pkg[:1]) + pkg[1:] + name
	}
	g.names[name] = t
	g.done[t] = name
	var fields []string
	g.fields(t, &fields)
	g.out = append(g.out, fmt.Sprintf("export interface %s {\n%s}\n", name, strings.Join(fields, "")))
	return name
}

func (g *gen) fields(t reflect.Type, out *[]string) {
	for i := range t.NumField() {
		f := t.Field(i)
		tag := f.Tag.Get("json")
		if tag == "-" {
			continue
		}
		if f.Anonymous && tag == "" && f.Type.Kind() == reflect.Struct {
			g.fields(f.Type, out)
			continue
		}
		if !f.IsExported() {
			continue
		}
		name, opts, _ := strings.Cut(tag, ",")
		if name == "" {
			name = f.Name
		}
		opt := ""
		if slices.Contains(strings.Split(opts, ","), "omitempty") {
			opt = "?"
		}
		*out = append(*out, fmt.Sprintf("  %s%s: %s;\n", name, opt, g.ts(f.Type)))
	}
}
